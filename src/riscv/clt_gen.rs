//! Writes the `.clt` test suites of the RISC-V circuits and of the shared
//! blocks they introduced (ADDER_KS5, DECODER_3_8/5_32, MUX_32_1_BUS,
//! REG_FILE_32):
//!
//! ```text
//! cargo test --release --lib riscv::clt_gen -- --ignored
//! ```
//!
//! The expected values come from our simulator. The circuits themselves are
//! checked against Rust references and the instruction-level simulator
//! (`tests.rs`, `cpu_tests.rs`); the suites pin that behaviour down for
//! `test` and for `verify-verilog`, which runs them on the exported netlists.

use std::collections::HashMap;
use std::fmt::Write;
use std::path::Path;

use crate::circuit::Circuit;

use super::asm::assemble;
use super::isa::csr;
use super::machine::Machine;
use super::tests::builder;

/// The tests' xorshift generator, with u128 values for the suites.
struct Rng(super::tests::Rng);

impl Rng {
    fn new(seed: u64) -> Rng {
        Rng(super::tests::Rng(seed))
    }

    fn next(&mut self) -> u128 {
        self.0.next() as u128
    }

    fn word(&mut self) -> u128 {
        self.0.word() as u128
    }
}

const GENERATED: &str = "Generated by `cargo test --release --lib riscv::clt_gen -- --ignored`\n\
// from the simulator; the circuit is checked against Rust references and the\n\
// instruction-level simulator in src/riscv/tests.rs and cpu_tests.rs.";

/// One suite under construction: drives the circuit and writes the commands.
struct Suite {
    c: Circuit,
    /// Port name -> (width, is a bus).
    ports: HashMap<String, (usize, bool)>,
    outputs: Vec<String>,
    text: String,
    /// Last asserted value per output, for `check_changed`.
    last: HashMap<String, u128>,
}

impl Suite {
    fn new(name: &str) -> Suite {
        let b = builder();
        let view = b.describe(name).unwrap_or_else(|| panic!("{name} unknown"));
        let mut ports = HashMap::new();
        for p in view.inputs.iter().chain(&view.outputs) {
            ports.insert(p.name.clone(), (p.width.unwrap_or(1), p.width.is_some()));
        }
        let outputs = view.outputs.iter().map(|p| p.name.clone()).collect();
        let c = b.build(name);
        c.evaluate_stable();
        Suite { c, ports, outputs, text: format!("TESTS FOR {name} {{\n"), last: HashMap::new() }
    }

    fn fmt(&self, name: &str, width: usize, bus: bool, v: u128) -> String {
        if bus {
            format!("{name}[{}:0] 0x{v:0d$X}", width - 1, d = width.div_ceil(4))
        } else {
            format!("{name} {v}")
        }
    }

    fn port(&self, name: &str) -> (usize, bool) {
        *self.ports.get(name).unwrap_or_else(|| panic!("no port {name}"))
    }

    fn read(&self, name: &str, width: usize, bus: bool) -> u128 {
        if !bus {
            return self.c.get_wire_value(name) as u128;
        }
        (0..width).fold(0, |acc, i| acc | (self.c.get_wire_value(&format!("{name}.{i}")) as u128) << i)
    }

    fn test(&mut self, name: &str) {
        writeln!(self.text, "    TEST \"{name}\" {{").unwrap();
    }

    fn end(&mut self) {
        self.text += "    }\n\n";
    }

    fn comment(&mut self, line: &str) {
        writeln!(self.text, "        // {line}").unwrap();
    }

    /// SET inputs (values masked to their width) without evaluating.
    fn set(&mut self, values: &[(&str, u128)]) {
        let items: Vec<String> = values
            .iter()
            .map(|&(name, v)| {
                let (w, bus) = self.port(name);
                let v = if w >= 128 { v } else { v & ((1 << w) - 1) };
                if bus {
                    for i in 0..w {
                        self.c.set_input(&format!("{name}.{i}"), v >> i & 1 == 1);
                    }
                } else {
                    self.c.set_input(name, v == 1);
                }
                self.fmt(name, w, bus, v)
            })
            .collect();
        writeln!(self.text, "        SET {};", items.join(", ")).unwrap();
    }

    fn eval(&mut self) {
        self.c.evaluate_stable();
        self.text += "        EVAL;\n";
    }

    /// One rising and falling edge of CLK.
    fn clock(&mut self) {
        for v in [true, false] {
            self.c.set_input("CLK", v);
            self.c.evaluate_stable();
        }
        self.text += "        SEQ CLK 0 -> CLK 1 -> CLK 0;\n";
    }

    fn assert_line(&mut self, items: Vec<String>) {
        if !items.is_empty() {
            let line: Vec<String> = items.iter().map(|i| format!("ASSERT {i};")).collect();
            writeln!(self.text, "        {}", line.join(" ")).unwrap();
        }
    }

    /// ASSERT the given outputs (or internal buses `name:width`).
    fn check(&mut self, names: &[&str]) {
        let items = names
            .iter()
            .map(|n| {
                let (name, w, bus) = match n.split_once(':') {
                    Some((name, w)) => (name, w.parse().unwrap(), true),
                    None => {
                        let (w, bus) = self.port(n);
                        (*n, w, bus)
                    }
                };
                let v = self.read(name, w, bus);
                self.last.insert(name.to_string(), v);
                self.fmt(name, w, bus, v)
            })
            .collect();
        self.assert_line(items);
    }

    fn check_all(&mut self) {
        let outputs = self.outputs.clone();
        self.check(&outputs.iter().map(String::as_str).collect::<Vec<_>>());
    }

    /// ASSERT the outputs whose value changed since they were last asserted.
    fn check_changed(&mut self) {
        let outputs = self.outputs.clone();
        let changed: Vec<&str> = outputs
            .iter()
            .filter(|n| {
                let (w, bus) = self.port(n);
                self.last.get(*n) != Some(&self.read(n, w, bus))
            })
            .map(String::as_str)
            .collect();
        self.check(&changed);
    }

    fn write(mut self, path: &str, header: &str) {
        self.text.truncate(self.text.trim_end().len());
        self.text += "\n}\n";
        let file = format!("// {header}\n//\n// {GENERATED}\n\n{}", self.text);
        let full = Path::new(env!("CARGO_MANIFEST_DIR")).join(path);
        std::fs::write(&full, file).unwrap_or_else(|e| panic!("{path}: {e}"));
        eprintln!("wrote {path}");
    }
}

/// Combinational suite: `n` vectors from `inputs`, all outputs asserted.
fn combinational(name: &str, path: &str, header: &str, n: usize, mut inputs: impl FnMut(&mut Rng, usize) -> Vec<(&'static str, u128)>) {
    let mut s = Suite::new(name);
    let mut rng = Rng::new(0xC17 ^ name.len() as u64);
    let per_test = 10;
    for t in 0..n.div_ceil(per_test) {
        s.test(&format!("vectors {}..{}", t * per_test, ((t + 1) * per_test).min(n) - 1));
        for k in t * per_test..((t + 1) * per_test).min(n) {
            let v = inputs(&mut rng, k);
            s.set(&v);
            s.eval();
            s.check_all();
        }
        s.end();
    }
    s.write(path, header);
}

fn one_hot4(d: u128) -> u128 {
    1 << (d & 15)
}

