/// The CSR addresses CSR_RV32 knows, plus some it does not.
fn csr_addresses() -> Vec<u16> {
    let mut v: Vec<u16> = csr::NAMES.iter().map(|&(_, n)| n).collect();
    v.extend([0x7C0, 0x302, 0xB03, 0xF11]);
    v
}

fn shared_blocks() {
    combinational("ADDER_KS5<32>", "src/circuits/adder/ADDER_KS5.clt", "Tests for ADDER_KS5<W> (Kogge-Stone adder) at W = 32", 40, |r, _| {
        vec![("A", r.word()), ("B", r.word()), ("Cin", r.next() & 1)]
    });
    combinational("DECODER_3_8", "src/circuits/decoder/DECODER_3_8.clt", "Tests for DECODER_3_8: every address, enabled and disabled", 16, |_, k| {
        vec![("A", k as u128 & 7), ("Enable", (k < 8) as u128)]
    });
    combinational("DECODER_5_32", "src/circuits/decoder/DECODER_5_32.clt", "Tests for DECODER_5_32: every address, plus some disabled", 40, |_, k| {
        vec![("A", (k as u128 * 7) & 31), ("Enable", (k < 32) as u128)]
    });
    combinational("MUX_32_1_BUS<4>", "src/circuits/mux/MUX_32_1_BUS.clt", "Tests for MUX_32_1_BUS<W> at W = 4 (input k = In[4k .. 4k+3]): every select", 32, |r, k| {
        // 128 input bits: four random words.
        vec![("In", r.next() | (r.next()) << 64), ("S", k as u128)]
    });

    // REG_FILE_32<32>: writes, reads of both ports, x0 stays 0.
    let mut s = Suite::new("REG_FILE_32<32>");
    let mut rng = Rng::new(32);
    let mut written = Vec::new();
    s.test("write every register, read it back on both ports");
    for r in 0..32u128 {
        let v = rng.word() | 1;
        written.push(v);
        s.set(&[("DataIn", v), ("WriteAddr", r), ("WriteEnable", 1), ("ReadAddrA", r), ("ReadAddrB", (r + 31) % 32)]);
        s.clock();
        s.eval();
        s.check_all();
    }
    s.end();
    s.test("disabled writes change nothing; random reads");
    for _ in 0..24 {
        let (a, b, w) = (rng.next() % 32, rng.next() % 32, rng.next() % 32);
        s.set(&[("DataIn", rng.word()), ("WriteAddr", w), ("WriteEnable", 0), ("ReadAddrA", a), ("ReadAddrB", b)]);
        s.clock();
        s.eval();
        s.check_all();
    }
    s.end();
    s.write("src/circuits/memory/REG_FILE_32.clt", "Tests for REG_FILE_32<W> (x0 hardwired 0) at W = 32");
}

fn riscv_blocks() {
    combinational("SHIFTER_RV32", "circuits/riscv/SHIFTER_RV32.clt", "Tests for SHIFTER_RV32: sll, srl, sra by every kind of amount", 60, |r, k| {
        vec![("A", r.word()), ("Amt", if k < 32 { k as u128 } else { r.next() % 32 }), ("Left", r.next() & 1), ("Arith", r.next() & 1)]
    });
    combinational("ALU_RV32", "circuits/riscv/ALU_RV32.clt", "Tests for ALU_RV32: every function, with edge-case operands", 96, |r, k| {
        let f = (k % 8) as u128;
        vec![("A", r.word()), ("B", r.word()), ("F", f), ("Sub", ((k / 8) % 2) as u128), ("Arith", ((k / 16) % 2) as u128)]
    });
    combinational("IMM_RV32", "circuits/riscv/IMM_RV32.clt", "Tests for IMM_RV32: every immediate format (and none)", 60, |r, k| {
        let fmt = k % 6;
        let w = r.next() as u32 as u128;
        vec![("Ir", w), ("FmtI", (fmt == 0) as u128), ("FmtS", (fmt == 1) as u128), ("FmtB", (fmt == 2) as u128), ("FmtU", (fmt == 3) as u128), ("FmtJ", (fmt == 4) as u128)]
    });
    let words = sample_instructions();
    let n = words.len() + 40;
    combinational("CONTROL_RV32", "circuits/riscv/CONTROL_RV32.clt", "Tests for CONTROL_RV32: one of every instruction, then random (mostly illegal) words", n, move |r, k| {
        let w = if k < words.len() { words[k] } else { r.next() as u32 | if k % 2 == 0 { 3 } else { 0 } };
        vec![("Ir", w as u128)]
    });
    combinational("LSU_RV32", "circuits/riscv/LSU_RV32.clt", "Tests for LSU_RV32: every size, signedness and address offset", 64, |r, k| {
        vec![("Rs2", r.word()), ("Word", r.word()), ("Size", (k % 3) as u128), ("Unsigned", ((k / 3) % 2) as u128), ("Addr", ((k / 6) % 4) as u128)]
    });

    // CSR_RV32: random reads, writes, traps and mret on the clock edge.
    let mut s = Suite::new("CSR_RV32");
    let mut rng = Rng::new(0xC5);
    let addrs = csr_addresses();
    s.test("reset");
    s.set(&[("Reset", 1)]);
    s.clock();
    s.set(&[("Reset", 0)]);
    s.eval();
    s.check_all();
    s.end();
    for t in 0..6 {
        s.test(&format!("random accesses {t}"));
        for _ in 0..12 {
            let a = addrs[rng.next() as usize % addrs.len()] as u128;
            let trap = rng.next() % 6 == 0;
            let mret = !trap && rng.next() % 6 == 0;
            s.set(&[
                ("CsrHi", one_hot4(a >> 8)),
                ("CsrMid", one_hot4(a >> 4)),
                ("CsrLo", one_hot4(a)),
                ("Op", 1 + rng.next() % 3),
                ("Src", rng.word()),
                ("CsrWrite", (!trap && rng.next() % 2 == 0) as u128),
                ("Trap", trap as u128),
                ("CauseInt", rng.next() & 1),
                ("CauseCode", rng.next() & 15),
                ("TrapPc", rng.word()),
                ("TrapVal", rng.word()),
                ("Mret", mret as u128),
                ("Retire", rng.next() & 1),
                ("MTIP", rng.next() & 1),
                ("MEIP", rng.next() & 1),
            ]);
            s.eval();
            s.check_all();
            s.clock();
            s.check_all();
        }
        s.end();
    }
    s.write("circuits/riscv/CSR_RV32.clt", "Tests for CSR_RV32: reads, writes (set/clear), traps, mret, counters, interrupts");

    // MULDIV_RV32: every operation, step by step until Done, then Consume.
    let mut s = Suite::new("MULDIV_RV32");
    let mut rng = Rng::new(0x3D);
    s.test("reset");
    s.set(&[("Reset", 1)]);
    s.clock();
    s.set(&[("Reset", 0)]);
    s.eval();
    s.check_all();
    s.end();
    let names = ["mul", "mulh", "mulhsu", "mulhu", "div", "divu", "rem", "remu"];
    for k in 0..16 {
        let f = k % 8;
        let (a, b) = match k {
            12 => (0x8000_0000u128, 0xFFFF_FFFFu128), // -2^31 / -1
            13 | 14 => (rng.word(), 0),      // by zero
            _ => (rng.word(), rng.word()),
        };
        s.test(&format!("{} 0x{a:08X}, 0x{b:08X}", names[f]));
        s.set(&[("A", a), ("B", b), ("F", f as u128), ("Start", 1), ("Consume", 0)]);
        s.clock();
        s.set(&[("Start", 0)]);
        s.eval();
        s.check(&["Busy", "Done"]);
        for _ in 0..40 {
            if s.c.get_wire_value("Done") {
                break;
            }
            s.clock();
            s.check(&["Busy", "Done"]);
        }
        s.check_all();
        s.set(&[("Consume", 1)]);
        s.clock();
        s.set(&[("Consume", 0)]);
        s.eval();
        s.check(&["Busy", "Done"]);
        s.end();
    }
    s.write("circuits/riscv/MULDIV_RV32.clt", "Tests for MULDIV_RV32: every M operation, with division by zero and overflow");

    // IO_RV32: register accesses, the UART line and the timer.
    let mut s = Suite::new("IO_RV32");
    let mut rng = Rng::new(0x10);
    s.test("reset");
    s.set(&[("Reset", 1), ("Rx", 1)]);
    s.clock();
    s.set(&[("Reset", 0)]);
    s.eval();
    s.check_all();
    s.end();
    let regs = [0u128, 1, 2, 3, 4, 5, 6, 8, 9, 10, 11, 7, 12];
    for t in 0..5 {
        s.test(&format!("random accesses {t}"));
        for _ in 0..16 {
            let reg = regs[rng.next() as usize % regs.len()];
            let write = rng.next() % 2 == 0;
            // UART_DIV small, mtimecmp low half small: the line and MTIP move.
            let data = match reg {
                6 => rng.next() % 4,
                10 | 11 => rng.next() % 64,
                _ => rng.word(),
            };
            let en = [0xF, 0xF, 0x1, 0x2, 0x4, 0x8, 0x3, 0xC][rng.next() as usize % 8];
            s.set(&[
                ("Addr", 0x1000_0000 | reg << 2 | if rng.next() % 4 == 0 { 0x40 } else { 0 }),
                ("WData", data),
                ("ByteEn", en),
                ("Write", write as u128),
                ("DataRead", (!write && rng.next() % 2 == 0) as u128),
                ("GpioIn", rng.word()),
                ("Rx", (rng.next() % 4 != 0) as u128),
            ]);
            s.eval();
            s.check_all();
            s.clock();
            s.check_all();
        }
        s.end();
    }
    s.test("not the I/O region");
    s.set(&[("Addr", 0x0000_0008), ("Write", 1), ("WData", 0x1234_5678), ("ByteEn", 0xF), ("DataRead", 0)]);
    s.eval();
    s.check_all();
    s.clock();
    s.set(&[("Addr", 0x2000_0008), ("Write", 0)]);
    s.eval();
    s.check_all();
    s.end();
    s.write("circuits/riscv/IO_RV32.clt", "Tests for IO_RV32: GPIO, display, UART registers and line, mtime/mtimecmp, byte lanes");
}

/// Program-flow suites: the harness plays the memory as `Machine` does,
/// clock by clock: SET the inputs it presents, ASSERT the outputs that
/// changed, one clock edge. At the end every output and the registers.
fn program_suite(top: &str, path: &str, header: &str, programs: &[(&str, &str)]) {
    let mut s = Suite::new(top);
    let soc = s.c.has_wire("Tx");
    for &(name, src) in programs {
        let words = assemble(src).unwrap_or_else(|e| panic!("{name}: {e}")).words;
        let mut m = Machine::new(&s.c, &words).unwrap();
        let inputs: Vec<&str> = if soc { vec!["DataIn", "Wait", "GpioIn", "Rx"] } else { vec!["DataIn", "Wait", "MTIP", "MEIP"] };
        s.test(name);
        for line in src.lines().map(str::trim).filter(|l| !l.is_empty()) {
            s.comment(line);
        }
        if soc {
            m.gpio_in = Some(0x0000_A5A5);
        }
        // The same inputs as the machine presents, written as SET.
        let present = |s: &mut Suite, m: &Machine| {
            m.serve(&s.c);
            let values: Vec<(&str, u128)> = inputs
                .iter()
                .map(|&n| {
                    let (w, bus) = s.port(n);
                    (n, s.read(n, w, bus))
                })
                .collect();
            s.set(&values);
        };
        s.set(&[("Reset", 1)]);
        for _ in 0..3 + if soc { 2 } else { 0 } {
            present(&mut s, &m);
            s.clock();
        }
        s.set(&[("Reset", 0)]);
        if soc {
            for _ in 0..2 {
                present(&mut s, &m);
                s.clock();
            }
        }
        s.last.clear();
        let mut after_halt = 0;
        for _ in 0..3000 {
            present(&mut s, &m);
            s.eval();
            s.check_changed();
            if m.halted(&s.c) {
                after_halt += 1;
                if !soc || after_halt > 60 {
                    break;
                }
            }
            m.clock(&s.c);
            s.text += "        SEQ CLK 0 -> CLK 1 -> CLK 0;\n";
        }
        assert!(m.halted(&s.c), "{name} did not halt");
        s.check_all();
        let prefix = if soc { "Cpu." } else { "" };
        let regs: Vec<String> = (1..32).map(|r| format!("{prefix}RegFile.R_{r}.Q:32")).collect();
        s.check(&regs.iter().map(String::as_str).collect::<Vec<_>>());
        s.end();
    }
    s.write(path, header);
}

